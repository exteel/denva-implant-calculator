// Copies the shared calculation engine (src/engine/v3) and the contracts into
// supabase/functions/_shared/engine so the `calculate` Edge Function (Deno)
// runs exactly the same code as the browser (ТЗ §8.1 determinism).
// Deno needs explicit .ts extensions, so relative imports are rewritten.
// Usage: node scripts/sync-engine.mjs [--check]
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "src/engine/v3");
const outDir = join(root, "supabase/functions/_shared/engine");
const HEADER = "// GENERATED by scripts/sync-engine.mjs from src/engine/v3 — do not edit.\n";

function rewrite(code) {
  return code
    .replace(/from "\.\.\/\.\.\/lib\/contracts"/g, 'from "./contracts.ts"')
    .replace(/from "\.\/([\w-]+)"/g, 'from "./$1.ts"');
}

export function buildEngineCopy() {
  const files = { "contracts.ts": HEADER + readFileSync(join(root, "src/lib/contracts.ts"), "utf8") };
  for (const name of readdirSync(srcDir)) {
    if (!name.endsWith(".ts") || name.endsWith(".test.ts") || name === "test-utils.ts") continue;
    files[name] = HEADER + rewrite(readFileSync(join(srcDir, name), "utf8"));
  }
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = buildEngineCopy();
  const check = process.argv.includes("--check");
  let stale = [];
  if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    const target = join(outDir, name);
    const current = existsSync(target) ? readFileSync(target, "utf8") : null;
    if (current !== content) {
      stale.push(name);
      if (!check) writeFileSync(target, content);
    }
  }
  if (check && stale.length) {
    console.error(`Engine copy is stale: ${stale.join(", ")}. Run: node scripts/sync-engine.mjs`);
    process.exit(1);
  }
  console.log(check ? "Engine copy is up to date." : `Synced ${Object.keys(files).length} files (${stale.length} changed).`);
}
